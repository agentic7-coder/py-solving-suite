"""Encoder module - Caesar cipher encoding"""

def encode(text, shift=3):
    """Encode text using Caesar cipher"""
    result = ""
    for char in text:
        if char.isalpha():
            ascii_offset = ord('A') if char.isupper() else ord('a')
            result += chr((ord(char) - ascii_offset + shift) % 26 + ascii_offset)
        else:
            result += char
    return result
